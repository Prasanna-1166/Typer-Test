// ---- Get lesson order by level ----
export function getLessonsForLevel(levelId: string): Lesson[] {
  return LESSONS.filter(l => l.levelId === levelId);
}

export function getModulesForLevel(levelId: string): Module[] {
  return MODULES.filter(m => m.levelId === levelId).sort((a, b) => a.order - b.order);
}

export function getLessonById(id: string): Lesson | undefined {
  return LESSONS.find(l => l.id === id);
}

export function getNextLesson(currentLessonId: string): Lesson | undefined {
  const idx = LESSONS.findIndex(l => l.id === currentLessonId);
  if (idx === -1) return undefined;
  return LESSONS[idx + 1];
}

export function getPrevLesson(currentLessonId: string): Lesson | undefined {
  const idx = LESSONS.findIndex(l => l.id === currentLessonId);
  if (idx <= 0) return undefined;
  return LESSONS[idx - 1];
}

// ---- Exported default course data ----
export function defaultCourseData(): CourseData {
  return {
    lessons: LESSONS,
    modules: MODULES,
    customLessons: [],
    schemaVersion: 1,
    lastModified: Date.now(),
  };
}

// ---- Get initial unlocked lessons for a level ----
export function getInitialUnlockedLessons(levelId: string): string[] {
  const lessons = getLessonsForLevel(levelId);
  if (lessons.length === 0) return [];
  return [lessons[0].id]; // Only first lesson unlocked initially
}

// ---- Check if lesson unlocks next ----
export function getUnlockedAfterCompletion(completedLessonId: string, completedLessonIds: string[]): string[] {
  const allCompleted = new Set([...completedLessonIds, completedLessonId]);
  const lessons = LESSONS;
  const newUnlocks: string[] = [];

  const idx = lessons.findIndex(l => l.id === completedLessonId);
  if (idx !== -1 && idx + 1 < lessons.length) {
    const next = lessons[idx + 1];
    if (next.levelId === lessons[idx].levelId && !allCompleted.has(next.id)) {
      newUnlocks.push(next.id);
    }
  }

  return newUnlocks;
}
